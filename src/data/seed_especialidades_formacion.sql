CREATE TABLE IF NOT EXISTS especialidades_formacion (
  cod_especialidad      int PRIMARY KEY,
  especialidad_formacion text NOT NULL,
  total_docentes        int DEFAULT 0,
  nivel_referencial     varchar(50) DEFAULT 'General',
  created_at            timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS relacion_especialidad (
  id                        serial PRIMARY KEY,
  especialidad_oficial_id   int NOT NULL REFERENCES especialidades_oficiales(id) ON DELETE CASCADE,
  cod_especialidad_formacion int NOT NULL REFERENCES especialidades_formacion(cod_especialidad) ON DELETE CASCADE,
  tipo_relacion             varchar(50) DEFAULT 'DIRECTA', -- 'DIRECTA', 'AFIN', 'EQUIVALENTE', 'TRANSVERSAL'
  ponderacion_pertinencia   varchar(20) DEFAULT 'ALTA',    -- 'ALTA', 'MEDIA', 'BAJA'
  observaciones             text,
  created_at                timestamptz DEFAULT now(),
  CONSTRAINT uq_esp_relacion UNIQUE (especialidad_oficial_id, cod_especialidad_formacion)
);

CREATE INDEX IF NOT EXISTS idx_rel_esp_oficial ON relacion_especialidad(especialidad_oficial_id);
CREATE INDEX IF NOT EXISTS idx_rel_esp_formacion ON relacion_especialidad(cod_especialidad_formacion);

